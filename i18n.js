let currentLang = localStorage.getItem('anichan_lang') || navigator.language.split('-')[0];
if (!LANG[currentLang]) currentLang = 'en';

function t(key) {
  const lang = LANG[currentLang] || LANG['en'];
  return lang[key] || LANG['en'][key] || key;
}

function setLanguage(lang) {
  if (!LANG[lang]) return;
  currentLang = lang;
  localStorage.setItem('anichan_lang', lang);
  location.reload();
}